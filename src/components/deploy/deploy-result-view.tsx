'use client';

/**
 * `/deploy` result view — **the seam F2 and F3 mount into.**
 *
 * ⚠️ This shell task (F3-F1) deliberately does NOT build the result cards. This
 * component provides:
 *   - the result-state chrome common to every plan: a repo header
 *     (`formatRepoLabel`), a confidence badge, a "used PRD context" note, and
 *     the "analyze another repo" affordance (no dead ends), and
 *   - three clearly-typed SLOTS that the downstream tasks fill:
 *       • `detectionSlot`  → F2: the stack summary card + expandable "how we know"
 *       • `fitsSlot`       → F3: the three provider-fit cards in score order
 *       • `configsSlot`    → F3: copyable/downloadable config artifacts
 *
 * Until those land, the slots render a labelled placeholder so the result state
 * is exercisable end-to-end from a fixture plan (acceptance criterion) without
 * anyone having to build the cards first. F2/F3 replace the placeholders by
 * passing the slot props from `deploy-client.tsx` — they do NOT edit this file's
 * chrome.
 *
 * The whole `DeployPlan` is passed through as `plan` so a slot component has
 * everything it needs; the slots are the mount points, `plan` is the data.
 */

import * as React from 'react';
import { Rocket, RotateCcw, FileCheck, Wrench } from 'lucide-react';

import type { DeployPlan } from '@/types/deploy';
import { formatRepoLabel } from '@/lib/deploy/repo-url';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { Card, CardContent } from '@/components/ui/card';

/** The props every seam slot receives. F2/F3 build components to this shape. */
export interface DeployResultSlotProps {
  plan: DeployPlan;
}

export interface DeployResultViewProps {
  plan: DeployPlan;
  /** Return to the input to analyze a different repo. */
  onAnalyzeAnother: () => void;
  /** F2 mounts the stack-detection summary + "how we know" here. */
  detectionSlot?: React.ReactNode;
  /** F3 mounts the three provider-fit cards here. */
  fitsSlot?: React.ReactNode;
  /** F3 mounts the generated config artifacts here. */
  configsSlot?: React.ReactNode;
}

/** Human copy + badge variant for the four confidence levels. */
const CONFIDENCE_META: Record<
  DeployPlan['detection']['confidence'],
  { label: string; variant: 'default' | 'secondary' | 'outline' | 'destructive' }
> = {
  high: { label: 'High confidence', variant: 'default' },
  medium: { label: 'Medium confidence', variant: 'secondary' },
  low: { label: 'Low confidence', variant: 'outline' },
  unknown: { label: "Couldn\u2019t read the repo", variant: 'destructive' },
};

/** A labelled placeholder shown until a downstream task fills a slot. */
function SlotPlaceholder({ icon, title, note }: { icon: React.ReactNode; title: string; note: string }) {
  return (
    <Card className="border-dashed">
      <CardContent className="flex flex-col items-center gap-2 py-8 text-center">
        <span className="text-muted-foreground" aria-hidden>
          {icon}
        </span>
        <p className="text-sm font-medium">{title}</p>
        <p className="max-w-md text-xs text-muted-foreground text-balance">{note}</p>
      </CardContent>
    </Card>
  );
}

export function DeployResultView({
  plan,
  onAnalyzeAnother,
  detectionSlot,
  fitsSlot,
  configsSlot,
}: DeployResultViewProps) {
  const confidence = CONFIDENCE_META[plan.detection.confidence];

  return (
    <div className="mx-auto flex w-full max-w-3xl flex-col gap-6">
      <header className="flex flex-col gap-3 sm:flex-row sm:items-start sm:justify-between">
        <div className="flex min-w-0 flex-col gap-1">
          <div className="flex items-center gap-2">
            <Rocket className="size-5 shrink-0 text-primary" aria-hidden />
            <h1 className="truncate font-mono text-lg font-semibold tracking-tight">
              {formatRepoLabel(plan.repo)}
            </h1>
          </div>
          <div className="flex flex-wrap items-center gap-2">
            <Badge variant={confidence.variant}>{confidence.label}</Badge>
            {plan.usedPrdContext ? (
              <Badge variant="outline" className="gap-1">
                <FileCheck className="size-3" aria-hidden />
                Used your PRD
              </Badge>
            ) : null}
          </div>
        </div>
        <Button
          type="button"
          variant="outline"
          size="sm"
          onClick={onAnalyzeAnother}
          className="shrink-0 gap-2"
        >
          <RotateCcw className="size-4" />
          Analyze another repo
        </Button>
      </header>

      {/* F2: stack detection + "how we know" */}
      {detectionSlot ?? (
        <SlotPlaceholder
          icon={<Wrench className="size-6" />}
          title="Stack detection mounts here (F2)"
          note="The stack summary card — framework, runtime, app shape, needs — plus the expandable 'how we know' list of cited file signals will render in this slot."
        />
      )}

      {/* F3: provider fits */}
      {fitsSlot ?? (
        <SlotPlaceholder
          icon={<Rocket className="size-6" />}
          title="Provider fits mount here (F3)"
          note="Vercel, Netlify and Render, in score order, each with its verdict, reasons, caveats and a one-click deploy button into the provider's own flow."
        />
      )}

      {/* F3: generated config artifacts */}
      {configsSlot ??
        (plan.configs.length > 0 ? (
          <SlotPlaceholder
            icon={<FileCheck className="size-6" />}
            title="Generated configs mount here (F3)"
            note={`This plan carries ${plan.configs.length} config artifact${plan.configs.length === 1 ? '' : 's'} (e.g. render.yaml) that will render as copyable, downloadable snippets.`}
          />
        ) : null)}
    </div>
  );
}
